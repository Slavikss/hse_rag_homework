"""Optional retrieval controller; the evaluated default RAG keeps its frozen prompt."""
from rag.system import RAG,ANSWER


class AgenticRAG(RAG):
    def __init__(self):
        super().__init__()
        self.answer_prompt=ANSWER+'''
Ты также управляешь инструментами поиска. Полный каталог доступных документов приведён ниже.
Перед окончательным ответом сопоставь ВСЕ части вопроса с найденными страницами.
Если хотя бы по одной запрошенной организации, периоду или величине сведений нет, а подходящий отчёт есть в каталоге, верни непустые searches с точными doc_ids из каталога или read_pages. Не заканчивай работу сообщением «по предоставленным страницам нет данных», пока можно поискать в доступных отчётах.
На промежуточном шаге answer может быть пустой строкой: новые запросы будут реально выполнены, после чего ты получишь дополнительные страницы.
Когда данные найдены, верни окончательный ответ, а searches и read_pages оставь пустыми. Если пришло сообщение «Это последний поиск», заверши ответ теми данными, которые подтверждены, честно отметив пробелы.
Не приписывай цифры одного банка другому: doc_id и организация должны совпадать с вопросом.
КАТАЛОГ:
'''+self.catalog
